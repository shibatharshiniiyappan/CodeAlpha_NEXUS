const LOCAL_STORAGE_KEY = 'nexus_smart_city_alerts_state_v1';

export function getStoredAlerts(): Alert[] {
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Could not read alerts from localStorage', e);
  }
  return INITIAL_ALERTS;
}

export function saveStoredAlerts(alerts: Alert[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(alerts));
  } catch (e) {
    console.warn('Could not write alerts to localStorage', e);
  }
}
